#!/usr/bin/env node
/**
 * Regenerates src/module-registry.ts and src/stable.ts from the current
 * contents of src/modules/ (files starting with '_' are private shared
 * implementations, not real core-js module ids, and are excluded).
 *
 * Run this after scripts/generate-modules.mjs adds new modules.
 *
 * Usage: node scripts/regenerate-registry.mjs
 */
import { readdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const MODULES_DIR = resolve(import.meta.dirname, '../src/modules');
const SRC_DIR = resolve(import.meta.dirname, '../src');

const ids = readdirSync(MODULES_DIR)
  .map((f) => f.replace(/\.ts$/, ''))
  .filter((id) => !id.startsWith('_'))
  .sort();

const registryLines = ids.map((id) => `  '${id}': true,`).join('\n');
const registry = `/**
 * Every module spackle has actually ported, keyed by core-js-compat module id
 * (reusing that id scheme purely as spec-shape naming -- no core-js code
 * involved). Adding a ported module = adding one entry here.
 *
 * Files starting with '_' (e.g. _reflect-impl.ts) are private shared
 * implementations, not real core-js module ids, and are deliberately
 * excluded here.
 *
 * Regenerated by scripts/regenerate-registry.mjs -- don't hand-edit, re-run
 * that script instead so it stays in sync with src/modules/*.ts.
 */
export const moduleRegistry = {
${registryLines}
} as const;

export type SpackleModuleId = keyof typeof moduleRegistry;

export const isRegisteredModule = (name: string): name is SpackleModuleId =>
  Object.prototype.hasOwnProperty.call(moduleRegistry, name);

export const spackleModuleSpecifier = (name: SpackleModuleId): string =>
  \`@shim-works/spackle/modules/\${name}\`;
`;
writeFileSync(resolve(SRC_DIR, 'module-registry.ts'), registry);

const stableLines = ids.map((id) => `import './modules/${id}.js';`).join('\n');
const stable = `/**
 * Non-Babel fallback: importing this unconditionally installs every ported
 * module, same as \`core-js/stable\`. When run through the spackle Babel
 * plugin, \`import "@shim-works/spackle/stable"\` gets replaced with only the
 * modules the configured targets actually need instead.
 */
${stableLines}
`;
writeFileSync(resolve(SRC_DIR, 'stable.ts'), stable);

console.log(`Wrote module-registry.ts and stable.ts with ${ids.length} entries.`);
